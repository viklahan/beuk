// The source catalogue the world generator draws from (committed as
// tools/sim/catalog.json, so the generator and its determinism test need
// neither the stack nor the source files):
//   - the studio's own sample book (SAMPLE_SECTIONS in client/index.html),
//   - the Ramp gallery books (<RAMP>/*.beuk-backup.json),
//   - the public-domain sagas prepared by gutenberg.mjs (<SAGAS>/_prepared).
// Each entry records the source file's sha256, so a later run can prove it
// built from exactly these bytes.
//   node tools/sim/catalog.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sha256, stableJson } from './lib.mjs';
import { SAGAS_DIR, allVolumes } from './gutenberg.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');
export const RAMP_DIR = process.env.SIM_RAMP_DIR || 'C:\\Users\\vikra\\Projects\\beuk-whole-project\\10-ramp-gallery\\books';

const words = (t) => String(t || '').split(/\s+/).filter(Boolean).length;
const paras = (t) => String(t || '').split(/\n\s*\n/).map((x) => x.trim()).filter(Boolean).length;
const secRow = (s, i) => ({ i, kind: s.kind, type: s.type, title: s.title || '', words: words(s.content), paras: paras(s.content) });

function sampleSections() {
  const html = readFileSync(path.join(REPO, 'client', 'index.html'), 'utf8');
  const m = /const SAMPLE_SECTIONS = (\[.*\]);\s*$/m.exec(html);
  if (!m) throw new Error('SAMPLE_SECTIONS not found in client/index.html');
  return { json: m[1], sections: JSON.parse(m[1]) };
}

export function buildCatalog() {
  const sources = [];
  const sm = sampleSections();
  sources.push({ key: 'sample', kind: 'sample', file: 'client/index.html#SAMPLE_SECTIONS', sha256: sha256(sm.json), title: 'The Lantern Coast', author: 'April Carooke', sections: sm.sections.map(secRow) });
  for (const f of readdirSync(RAMP_DIR).filter((x) => x.endsWith('.beuk-backup.json')).sort()) {
    if (f.startsWith('the-lantern-coast')) continue; // the sample itself, in its print dress: the studio's own sample is used instead
    const raw = readFileSync(path.join(RAMP_DIR, f));
    const b = JSON.parse(raw.toString('utf8')).book;
    sources.push({ key: f.replace(/^ramp-/, '').replace(/\.beuk-backup\.json$/, ''), kind: 'ramp', file: f, sha256: sha256(raw), title: b.meta.title, author: b.meta.author, images: (b.images || []).length, sections: b.sections.map(secRow) });
  }
  const prepDir = path.join(SAGAS_DIR, '_prepared');
  const sagas = [];
  for (const v of allVolumes()) {
    const md = path.join(prepDir, `pg${v.ebook}.md`);
    if (!existsSync(md)) throw new Error('not prepared: ' + md + ' (run gutenberg.mjs fetch && prep)');
    const text = readFileSync(md, 'utf8');
    const imgs = JSON.parse(readFileSync(path.join(prepDir, `pg${v.ebook}.images.json`), 'utf8'));
    sagas.push({ ebook: v.ebook, title: v.title, series: v.series, seriesKey: v.seriesKey, order: v.order, persona: v.persona, author: v.author, mdSha256: sha256(text), mdBytes: Buffer.byteLength(text), chapters: (text.match(/^## Chapter /gm) || []).length, words: words(text.replace(/^---[\s\S]*?---/, '').replace(/^!\[.*$/gm, '').replace(/^## .*$/gm, '')), images: imgs.length, imageBytes: imgs.reduce((a, b) => a + b.bytes, 0) });
  }
  return { note: 'Generated by tools/sim/catalog.mjs. Word counts here are whitespace splits for planning only; every measured count in the report comes from the studio itself.', sources, sagas };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const cat = buildCatalog();
  writeFileSync(path.join(HERE, 'catalog.json'), stableJson(cat));
  console.log('catalog.json:', cat.sources.length, 'sources,', cat.sagas.length, 'saga volumes');
}
