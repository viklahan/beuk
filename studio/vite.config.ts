/// <reference types="vitest/config" />
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/* Beuk 2.0 studio. Served at /next (Caddy proxies /next* to the app,
   which serves client/next — see src/routes/next-studio.ts). The build
   output is not committed: the Dockerfile's studio stage makes it. */
const here = (p: string): string => fileURLToPath(new URL(p, import.meta.url));

type StringsMeta = { uiLangKey: string; themeKey: string; order: string[]; rtl: string[] };
const stringsMeta = (): StringsMeta => {
  try {
    return JSON.parse(readFileSync(here('./src/generated/strings-meta.json'), 'utf8')) as StringsMeta;
  } catch {
    throw new Error('studio/src/generated/ is missing: run `npm run extract` (the build does it first)');
  }
};

/* index.html's pre-paint script gets 1.0's keys and language tables
   from the extraction (one source), and the page links 1.0's self-hosted
   fonts at /assets/fonts/ (same origin, served by Caddy from client/;
   the same two faces 1.0 preloads for its first paint). The font tags go
   in after Vite's own HTML processing, so it leaves those URLs alone. */
function beukHtml(): Plugin[] {
  return [
    {
      name: 'beuk-html-one-source',
      transformIndexHtml: {
        order: 'pre',
        handler(html) {
          const m = stringsMeta();
          const fills: Record<string, string> = {
            __BEUK_THEME_KEY__: JSON.stringify(m.themeKey),
            __BEUK_LANG_KEY__: JSON.stringify(m.uiLangKey),
            __BEUK_LANGS__: JSON.stringify(m.order),
            __BEUK_RTL__: JSON.stringify(m.rtl),
          };
          let out = html;
          for (const [k, v] of Object.entries(fills)) {
            if (!out.includes(k)) throw new Error(`studio/index.html no longer carries ${k}`);
            out = out.split(k).join(v);
          }
          return out;
        },
      },
    },
    {
      name: 'beuk-html-fonts',
      transformIndexHtml: {
        order: 'post',
        handler() {
          const icon = { tag: 'link', attrs: { rel: 'icon', href: ICON_FILE }, injectTo: 'head' as const };
          return [icon, ...FONT_FILES.map((href) =>
            href.endsWith('.css')
              ? { tag: 'link', attrs: { rel: 'stylesheet', href }, injectTo: 'head' as const }
              : { tag: 'link', attrs: { rel: 'preload', href, as: 'font', type: 'font/woff2', crossorigin: '' }, injectTo: 'head' as const },
          )];
        },
      },
    },
  ];
}

/* The service worker's precache list (public/sw.js reads it with
   importScripts). Every file of the build, from Vite's own manifest
   (build.manifest), plus the shell page; 1.0's fonts and icon are optional
   (the worker serves those stale-while-revalidate: same name on change). The
   cache name carries a hash of the list and the page, so each build
   gets its own cache and the old one is retired on activate. */
function precacheList(): Plugin {
  const BASE = '/next/';
  return {
    name: 'beuk-precache',
    apply: 'build',
    writeBundle(options, bundle) {
      const outDir = options.dir!;
      const manifestAsset = bundle['.vite/manifest.json'];
      if (!manifestAsset || manifestAsset.type !== 'asset') throw new Error('beuk-precache: no .vite/manifest.json in the bundle (build.manifest must be true)');
      type Entry = { file: string; css?: string[]; assets?: string[] };
      const manifest = JSON.parse(String(manifestAsset.source)) as Record<string, Entry>;
      const files = new Set<string>();
      for (const e of Object.values(manifest)) {
        files.add(e.file);
        for (const f of e.css ?? []) files.add(f);
        for (const f of e.assets ?? []) files.add(f);
      }
      // wave 3a: 1.0's Zen paintings too (1.0's sw.js precaches them "so Zen is whole offline"); the sounds, as in 1.0,
      // are not precached
      const assets = [...[...files].sort(), ...ZEN_MEDIA.filter((f) => f.endsWith('.webp')).map((f) => 'assets/' + f)].map((f) => BASE + f);
      if (!assets.some((a) => a.endsWith('.js'))) throw new Error('beuk-precache: the manifest lists no script');
      const html = readFileSync(path.join(outDir, 'index.html'), 'utf8');
      const sw = readFileSync(path.join(outDir, 'sw.js'), 'utf8');
      const hash = createHash('sha256').update(html).update('|').update(assets.join(',')).update('|').update(sw).digest('hex').slice(0, 12);
      const list = { cache: 'beuk-next-' + hash, shell: BASE + 'index.html', assets, optional: [...FONT_FILES, ICON_FILE] };
      const head = '/* GENERATED by vite.config.ts (beuk-precache) from the build manifest: the service worker precache list. */';
      writeFileSync(path.join(outDir, 'sw-precache.js'), [head, 'self.BEUK_NEXT = ' + JSON.stringify(list, null, 1) + ';', ''].join('\n'));
    },
  };
}

/* Wave 3a: 1.0's Zen code (lifted whole, one source) asks for its paintings and sounds RELATIVE to the page
   ("assets/zen/<id>.webp" as a background image; new URL("assets/sound/<scene>.mp3", document.baseURI)), which at
   /studio is /assets/…; at /next/ the same words name /next/assets/…. The build copies 1.0's files there, byte for
   byte (test/environment.test.tsx compares them): the same files, fetched same-origin, nothing synthesised. */
export const ZEN_MEDIA = ['zen/bliss.webp', 'zen/calm.webp', 'zen/mind.webp', 'zen/sakura.webp', 'sound/rain.mp3', 'sound/waves.mp3', 'sound/wind.mp3'];
function zenMedia(): Plugin {
  return {
    name: 'beuk-zen-media',
    apply: 'build',
    writeBundle(options) {
      const outDir = options.dir!;
      for (const f of ZEN_MEDIA) {
        const to = path.join(outDir, 'assets', f);
        mkdirSync(path.dirname(to), { recursive: true });
        copyFileSync(here('../client/assets/' + f), to);
      }
    },
  };
}

/** 1.0's tab icon (client/index.html <link rel="icon">). */
export const ICON_FILE = '/assets/logo.webp';

/** 1.0's first-paint faces (client/index.html <head>) and their stylesheet. */
export const FONT_FILES = [
  '/assets/fonts/karla/karla-latin-normal-400_500_600_700.woff2',
  '/assets/fonts/ebgaramond/ebgaramond-latin-normal-400_500_600.woff2',
  '/assets/fonts/fonts.css',
];

/** A package's ESM entry in the studio's node_modules (exports["."].import, else module, else main). */
function esmEntry(name: string): string {
  const dir = here(`./node_modules/${name}/`);
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')) as {
    exports?: Record<string, unknown>; module?: string; main?: string;
  };
  const dot = (pkg.exports && ('.' in pkg.exports ? pkg.exports['.'] : pkg.exports)) as Record<string, unknown> | string | undefined;
  const imp = typeof dot === 'string' ? dot : dot && (dot.import as string | { default?: string } | undefined);
  const file = (typeof imp === 'string' ? imp : imp?.default) ?? pkg.module ?? pkg.main;
  if (!file) throw new Error(`${name}: no ESM entry in its package.json`);
  return path.join(dir, file);
}

/** The bare packages src/book/editor imports (besides zod). */
export const BOOK_DEPS = ['yjs', 'y-prosemirror', 'prosemirror-model', 'prosemirror-state', 'prosemirror-view', 'prosemirror-transform'];

export default defineConfig({
  base: '/next/',
  plugins: [react(), ...beukHtml(), precacheList(), zenMedia()],
  resolve: {
    alias: [
      /* The book-format code is imported straight from the server's
         src/book (one source), never copied. */
      { find: '@book', replacement: here('../src/book') },
      /* src/book imports zod; files outside studio/ would otherwise look
         for it in the repo root's node_modules. Same pinned version. */
      { find: 'zod', replacement: here('./node_modules/zod') },
      /* src/book/editor imports Yjs and ProseMirror the same way: each bare
         name points at the studio copy's ESM entry, the very file Node and
         Vite pick for every other importer (y-indexeddb, y-tiptap, TipTap).
         So the bundle, and the tests, hold ONE yjs and one of each
         prosemirror package (two copies break instanceof and Yjs's "already
         imported" check; test/dedupe.test.ts asserts it). */
      ...BOOK_DEPS.map((d) => ({ find: new RegExp(`^${d}$`), replacement: esmEntry(d) })),
    ],
    dedupe: [...BOOK_DEPS, 'lib0', 'y-protocols'],
  },
  build: {
    outDir: here('../client/next'),
    emptyOutDir: true,
    manifest: true,
    target: 'es2022',
    sourcemap: false,
  },
  server: { fs: { allow: [here('.'), here('../src/book')] } },
  test: {
    globalSetup: ['test/global-setup.ts'],
    /* Tests import src/book/studio/closure.ts (1.0's t() beside ours, the
       extraction's failures). Its `typescript` import resolves from the
       repo root, which the studio does not install: use the studio's. */
    alias: { typescript: here('./node_modules/typescript') },
    environment: 'jsdom',
    include: ['test/**/*.test.{ts,tsx}'],
    pool: 'forks',
    maxWorkers: 1,
  },
});
