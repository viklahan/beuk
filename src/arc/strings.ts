/**
 * The keys that stay English in every language, so no draft carries them:
 *   - the stamp and the added page's title (ruling F16: an unsigned
 *     translation inside a reader's EPUB cannot be recalled from a device);
 *   - the used-mail-link page (renderMailGonePage): a used Not me link
 *     names nobody any more, so there is no reader language to use.
 */
export const ARC_ENGLISH_ONLY = ['arc.stamp', 'arc.stampPage.title', 'arc.mail.goneTitle', 'arc.mail.gone'] as const satisfies readonly ArcKey[];
export type ArcDraftKey = Exclude<ArcKey, (typeof ARC_ENGLISH_ONLY)[number]>;
/** One UNSIGNED draft table: every key but the English-only ones (tsc
 *  refuses a missing or an extra key). */
type Draft = Record<ArcDraftKey, string>;

/*
 * The 14 UNSIGNED drafts (Task 9), written by Claude by hand — no
 * translation service or API was called; V signs off each one
 * (docs/strings-pending-signoff.md §9). Rules every draft keeps (checked
 * by tests/arc-strings.test.ts): the English keys less ARC_ENGLISH_ONLY;
 * the same {placeholders}; Amazon's rule (never "in exchange for a
 * review", never a review owed — "if you'd like to review it"); the form
 * of address of each studio pack (es/it tú, fr vous, de Sie, pt the third
 * person, nl u, pl Ty, ru вы, tr siz, ar the second person, hi आप,
 * mr तुम्ही, ja and zh-Hans as their packs).
 *
 * {author} is a name, or arc.theAuthor when the book names none, so a
 * draft keeps it where any name reads: German in the dative only (after
 * von/bei; the fallback is "dem Autor"); Polish and Russian in the
 * nominative only (no past-tense verb agrees with it, as those agree with
 * a gender); Turkish with no suffix on any placeholder; Italian and
 * Portuguese fall back to "chi l'ha scritto" / "quem o escreveu", which
 * no preposition contracts with; Spanish to "su autor".
 */

