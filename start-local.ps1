# Beuk — local startup (Windows / Docker Desktop).
#
# One command to get a clean local stack on http://localhost:8090,
# also reachable from other devices on this network (a tablet, another PC):
#   1. stops stray Beuk dev servers from ANY copy of the project
#      (node processes whose command line points into Projects\beuk*),
#   2. frees port 8090: stops any other Docker container publishing it,
#      and any non-Docker process listening on it,
#   3. builds and starts this stack (db + app + caddy), with the tools
#      overlay when tools-bin/epubcheck.jar is present,
#   4. waits for /api/health and prints the URL.
#
# Usage:  .\start-local.ps1            # start / restart
#         .\start-local.ps1 -Down      # stop this stack
#         .\start-local.ps1 -NoBuild   # restart without rebuilding images
#         .\start-local.ps1 -LocalOnly # this machine only (127.0.0.1)
#
# Network access is the default (V, 2026-10-29). It is plain http on the
# local network: the studio works, but browsers only allow its service
# worker (offline, install) on https or localhost. On an untrusted
# network (café Wi-Fi) run with -LocalOnly. -Lan is still accepted and
# changes nothing.

param(
  [switch]$Down,
  [switch]$NoBuild,
  [switch]$LocalOnly,
  [switch]$Lan,
  [int]$Port = 8090
)

# Not 'Stop': docker writes progress to stderr, which Windows PowerShell
# would turn into a terminating error. Native steps check $LASTEXITCODE.
$ErrorActionPreference = 'Continue'
$root = $PSScriptRoot
Set-Location $root
$project = 'beuk-saas'

function Note($msg) { Write-Host "[beuk] $msg" -ForegroundColor Cyan }
function Warn($msg) { Write-Host "[beuk] $msg" -ForegroundColor Yellow }

# Compose files: base, tools overlay (only if the tools are on disk), and
# the local port override (git-ignored, written fresh on every run so
# network and -LocalOnly switch cleanly). On the network the port listens on
# every interface and Caddy answers to any host name on that port (the
# .env DOMAIN names localhost only, so a tablet asking for 192.168.x.x
# would otherwise get nothing).
$Lan = -not $LocalOnly
$override = Join-Path $root 'docker-compose.override.yml'
$bind = if ($Lan) { "0.0.0.0" } else { "127.0.0.1" }
$caddyEnv = if ($Lan) { "`n    environment:`n      DOMAIN: `"http://:${Port}`"" } else { "" }
@"
# LOCAL ONLY (git-ignored): serve Beuk on port $Port instead of 80/443.
# Generated by start-local.ps1$(if ($Lan) { ' -Lan: reachable from this network' } else { ': localhost only' }).
services:
  caddy:
    ports: !override
      - "${bind}:${Port}:${Port}"$caddyEnv
"@ | Out-File -FilePath $override -Encoding utf8
Note "wrote docker-compose.override.yml ($bind`:$Port)"
$files = @('-f', 'docker-compose.yml')
if (Test-Path (Join-Path $root 'tools-bin\epubcheck.jar')) {
  $files += @('-f', 'deploy/docker-compose.tools.yml')
} else {
  Warn 'tools-bin/epubcheck.jar not found: EPUBCheck / PDF-X jobs will report "not configured".'
}
$files += @('-f', 'docker-compose.override.yml')
$compose = @('compose', '-p', $project) + $files

if ($Down) {
  & docker @compose down
  exit $LASTEXITCODE
}

if (-not (Test-Path (Join-Path $root '.env'))) {
  # Local values: plain HTTP on the override port (no dev CA, no 443).
  (Get-Content (Join-Path $root '.env.example')) `
    -replace '^DOMAIN=.*', "DOMAIN=http://localhost:$Port" `
    -replace '^APP_BASE_URL=.*', "APP_BASE_URL=http://localhost:$Port" `
    -replace '^COOKIE_SECURE=.*', 'COOKIE_SECURE=false' |
    Out-File -FilePath (Join-Path $root '.env') -Encoding utf8
  Warn '.env was missing: created from .env.example with local-only defaults.'
}

# 1. Stray Beuk dev servers from any copy of the project.
$strays = Get-CimInstance Win32_Process -Filter "Name = 'node.exe'" |
  Where-Object { $_.CommandLine -match '\\Projects\\beuk[^\\]*\\' }
foreach ($p in $strays) {
  Note "stopping stray node pid $($p.ProcessId): $($p.CommandLine.Substring(0, [Math]::Min(120, $p.CommandLine.Length)))"
  Stop-Process -Id $p.ProcessId -Force -ErrorAction SilentlyContinue
}

# 2a. Other containers publishing the port (not this compose project).
# (Labels are read via inspect: PowerShell 5.1 mangles quotes inside a
# native --format template argument.)
$holders = docker ps -q --filter "publish=$Port"
foreach ($id in $holders) {
  if (-not $id) { continue }
  $name = docker inspect -f '{{.Name}}' $id
  $proj = (docker inspect -f '{{json .Config.Labels}}' $id | ConvertFrom-Json).'com.docker.compose.project'
  if ($proj -eq $project) { continue }
  Note "stopping container $name (project '$proj') holding port $Port"
  docker stop $id | Out-Null
}

# 2b. Non-Docker listeners on the port.
$listeners = Get-NetTCPConnection -State Listen -LocalPort $Port -ErrorAction SilentlyContinue
foreach ($l in $listeners) {
  $proc = Get-Process -Id $l.OwningProcess -ErrorAction SilentlyContinue
  if (-not $proc -or $proc.ProcessName -match '^(com\.docker\.backend|wslrelay|vpnkit)') { continue }
  Note "stopping $($proc.ProcessName) pid $($proc.Id) listening on $Port"
  Stop-Process -Id $proc.Id -Force -ErrorAction SilentlyContinue
}

# 3. Up. The tools overlay builds FROM beuk-app:latest, so build the base first.
if (-not $NoBuild) {
  Note 'building images'
  & docker compose -p $project -f docker-compose.yml build app
  if ($LASTEXITCODE) { exit $LASTEXITCODE }
  & docker @compose build
  if ($LASTEXITCODE) { exit $LASTEXITCODE }
}
& docker @compose up -d --remove-orphans
if ($LASTEXITCODE) { exit $LASTEXITCODE }
# The Caddyfile is a bind mount: 'up' leaves a running caddy on its old
# config, so restart it to pick up any edit.
& docker @compose restart caddy | Out-Null

# 4. Health.
$url = "http://localhost:$Port"
for ($i = 0; $i -lt 60; $i++) {
  try {
    $r = Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 "$url/api/health"
    if ($r.StatusCode -eq 200) {
      Note "up: $url  ($($r.Content))"
      if ($Lan) {
        $ips = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
          Where-Object { $_.IPAddress -notmatch '^(127\.|169\.254\.)' -and $_.PrefixOrigin -ne 'WellKnown' } |
          Select-Object -ExpandProperty IPAddress
        foreach ($ip in $ips) { Note "on this network: http://${ip}:$Port" }
        Warn "plain http: offline mode and app install need https or localhost. If another device can't connect, allow TCP $Port in Windows Firewall (Private network)."
      }
      exit 0
    }
  } catch { }
  Start-Sleep -Seconds 2
}
Warn "no healthy /api/health after 120s; check: docker compose -p $project logs app"
exit 1
